test('layout training events, worker lifecycle, and model artifact upload/download are available in CLI',async()=>{
 const dir=await mkdtemp(join(tmpdir(),'omr-model-cli-')),file=join(dir,'weights.pt'),jsonFile=join(dir,'events.json'),id=randomUUID(),bytes=Buffer.from('checkpoint');
 await writeFile(file,bytes);await writeFile(jsonFile,JSON.stringify({events:[{seq:1,kind:'state',payload:{status:'running'}}]}));
 let calls=[];
 const request=async(url,options)=>{
   calls.push({url,options});
   if(url.endsWith('/artifacts/weights')&&options.method==='POST'){
     assert.equal(options.headers['X-Checksum-Sha256'],sha(bytes));
     assert.equal(options.headers['Content-Length'],String(bytes.length));
     const chunks=[];for await(const chunk of options.body)chunks.push(chunk);
     assert.deepEqual(Buffer.concat(chunks),bytes);
   }
   return Response.json({ok:true});
 };
 await invoke('layout training events append '+id,{input:jsonFile},request);
 assert.equal(JSON.parse(calls.at(-1).options.body).events[0].seq,1);
 await invoke('layout training artifacts upload '+id,{file,kind:'weights'},request);
 await invoke('layout inference workers heartbeat '+id,{input:jsonFile},request);
 assert.ok(calls.at(-1).url.endsWith('/workers/'+id+'/heartbeat'));
 await invoke('layout inference predictions claim',{input:jsonFile},request);
 assert.ok(calls.at(-1).url.endsWith('/predictions/claim'));
 await invoke('layout training runs complete '+id,{},request);
 assert.deepEqual(JSON.parse(calls.at(-1).options.body),{});
 await assert.rejects(invoke('layout training artifacts upload '+id,{file,kind:'unknown'},request),e=>e.code==='ARGUMENT');
 await invoke('layout training events list '+id,{after:'5'},request);
 assert.ok(calls.at(-1).url.endsWith('/events?after=5'));
});
test('CLI distribution includes all task, deployment and export modules and starts independently',async()=>{
 const dir=await mkdtemp(join(tmpdir(),'omr-task-package-'));
 const packed=spawnSync(process.execPath,['tools/package-cli.mjs','--output',dir],{encoding:'utf8'});
 assert.equal(packed.status,0,packed.stderr);
 const {archive,checksum}=JSON.parse(packed.stdout);
 assert.equal(sha(await readFile(archive)),checksum);
 const extracted=spawnSync('tar',['-xzf',archive,'-C',dir],{encoding:'utf8'});assert.equal(extracted.status,0,extracted.stderr);
 const root=join(dir,'xianji-omr-cli-'+VERSION),manifest=JSON.parse(await readFile(join(root,'manifest.json'),'utf8'));
 for(const required of ['src/tasks.mjs','src/deploy.mjs','src/export.mjs','src/localization.mjs'])assert.ok(manifest.files[required]);
 const help=spawnSync(process.execPath,[join(root,'xianji-omr.mjs'),'--help'],{cwd:dir,encoding:'utf8'});
 assert.equal(help.status,0,help.stderr);
 const result=JSON.parse(help.stdout);
 assert.ok(result.commands.includes('key-signatures datasets create'));
 assert.ok(result.commands.includes('layout inference predict'));
 assert.ok(result.commands.includes('localization datasets export'));
 assert.equal(result.version,VERSION);
});
