test('CLI key images and JSON exports are checksum verified and never overwrite existing files',async()=>{
 const dir=await mkdtemp(join(tmpdir(),'omr-key-download-')),dataset=randomUUID(),record=randomUUID(),data=Buffer.from('fixture download');
 const request=async()=>new Response(data,{headers:{'x-checksum-sha256':sha(data),'content-length':String(data.length)}});
 const output=join(dir,'key.png');
 await invoke('key-signatures records content '+record,{dataset,output},request);
 assert.deepEqual(await readFile(output),data);
 await assert.rejects(invoke('key-signatures records content '+record,{dataset,output},request),e=>e.code==='EXISTS');
 const exported=join(dir,'keys.json');
 await invoke('key-signatures datasets export '+dataset,{output:exported},request);
 assert.deepEqual(await readFile(exported),data);
 await assert.rejects(invoke('key-signatures records content '+record,{dataset},request),e=>e.code==='OUTPUT');
 await assert.rejects(invoke('key-signatures records content '+record,{dataset,output:join(dir,'bad.png')},async()=>new Response(data,{headers:{'x-checksum-sha256':'a'.repeat(64)}})),e=>e.code==='CHECKSUM');
 assert.equal((await readdir(dir)).includes('bad.png'),false);
 const race=join(dir,'race.png');
 const results=await Promise.allSettled([1,2].map(()=>invoke('key-signatures records content '+record,{dataset,output:race},request)));
 assert.equal(results.filter(r=>r.status==='fulfilled').length,1);
 assert.deepEqual(await readFile(race),data);
 assert.ok(!(await readdir(dir)).some(name=>name.endsWith('.part')));
});
